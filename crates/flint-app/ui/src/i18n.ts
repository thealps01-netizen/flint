export type Key = keyof typeof en;

/** The interface language comes from Settings (English by default). */
export function t(lang: Lang, key: Key, ...args: string[]): string {
  return (lang === "tr" ? tr : en)[key].replace(/\{(\d)\}/g, (_, i) => args[Number(i)] ?? "");
}
